const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("api", {
  loadSettings: () => ipcRenderer.invoke("settings:load"),
  saveSettings: s => ipcRenderer.invoke("settings:save", s),
  totalRam: () => ipcRenderer.invoke("system:ram"),
  listVersions: () => ipcRenderer.invoke("versions:list"),
  loginMicrosoft: () => ipcRenderer.invoke("auth:microsoft"),
  logout: () => ipcRenderer.invoke("auth:logout"),
  restoreLogin: () => ipcRenderer.invoke("auth:restore"),
  launch: opts => ipcRenderer.invoke("game:launch", opts),
  openMods: target => ipcRenderer.invoke("folder:mods", target),
  listMods: version => ipcRenderer.invoke("mods:list", { version }),
  toggleMod: opts => ipcRenderer.invoke("mods:toggle", opts),
  searchMods: opts => ipcRenderer.invoke("mods:search", opts),
  installMod: opts => ipcRenderer.invoke("mods:install", opts),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  listContent: opts => ipcRenderer.invoke("content:list", opts),
  searchContent: opts => ipcRenderer.invoke("content:search", opts),
  installContent: opts => ipcRenderer.invoke("content:install", opts),
  toggleContent: opts => ipcRenderer.invoke("content:toggle", opts),
  deleteContent: opts => ipcRenderer.invoke("content:delete", opts),
  openCrashReport: file => ipcRenderer.invoke("crash:open-report", file),
  diskScan: () => ipcRenderer.invoke("disk:scan"),
  diskClean: () => ipcRenderer.invoke("disk:clean"),
  diskDeleteVersion: opts => ipcRenderer.invoke("disk:delete-version", opts),
  diskOpen: () => ipcRenderer.invoke("disk:open"),
  getBackground: () => ipcRenderer.invoke("background:get"),
  chooseBackground: () => ipcRenderer.invoke("background:choose"),
  resetBackground: () => ipcRenderer.invoke("background:reset"),
  packName: () => ipcRenderer.invoke("pack:name"),
  fabricVersions: () => ipcRenderer.invoke("fabric:versions"),
  appVersion: () => ipcRenderer.invoke("app:version"),
  on: (channel, cb) => ipcRenderer.on(channel, (_e, data) => cb(data)),
});
